bool yyparse(const std::vector<Token>& input_tokens) {
  std::vector<Token> tokens = input_tokens;
  if (tokens.empty() || tokens.back().type != 0) {
    tokens.push_back({0, "", 0, 0, {}});
  }
  std::vector<int> states = {0};
  std::vector<SemanticValue> semantic_stack;
  RuntimeSymbolTable symbol_table;
  std::size_t index = 0;
  while (index < tokens.size()) {
    const int state = states.back();
    const int token = tokens[index].type;
    const auto action_it = kAction[static_cast<std::size_t>(state)].find(token);
    if (action_it == kAction[static_cast<std::size_t>(state)].end() || action_it->second == "err") {
      return false;
    }
    const std::string& action = action_it->second;
    if (action == "acc") {
      return true;
    }
    if (!action.empty() && action[0] == 's') {
      const int next_state = std::stoi(action.substr(1));
      states.push_back(next_state);
      if (token == '{') symbol_table.enterScope();
      if (token == '}') symbol_table.exitScope();
      SemanticValue shifted;
      shifted.symbol = tokenSymbol(token);
      shifted.lexeme = tokens[index].lexeme;
      shifted.value = tokens[index].semantic;
      if (shifted.value.lexeme.empty()) {
        shifted.value.lexeme = tokens[index].lexeme;
      }
      semantic_stack.push_back(shifted);
      ++index;
      continue;
    }
    if (!action.empty() && action[0] == 'r') {
      const int production = std::stoi(action.substr(1));
      const int pop_count = kProductionSize[static_cast<std::size_t>(production)];
      std::vector<SemanticValue> rhs(static_cast<std::size_t>(pop_count));
      for (int offset = pop_count - 1; offset >= 0; --offset) {
        rhs[static_cast<std::size_t>(offset)] = semantic_stack.back();
        semantic_stack.pop_back();
        states.pop_back();
      }
      observeReduction(production, rhs, &symbol_table);
      YYSTYPE yyval{};
      executeAction(production, rhs, &yyval);
      SemanticValue lhs_value;
      lhs_value.symbol = kProductionLeft[static_cast<std::size_t>(production)];
      lhs_value.value = yyval;
      for (const SemanticValue& value : rhs) {
        if (!value.lexeme.empty()) {
          lhs_value.lexeme = value.lexeme;
          break;
        }
      }
      if (lhs_value.value.lexeme.empty()) {
        lhs_value.value.lexeme = lhs_value.lexeme;
      }
      const int goto_state = kGoto[static_cast<std::size_t>(states.back())].at(lhs_value.symbol);
      states.push_back(goto_state);
      semantic_stack.push_back(lhs_value);
      continue;
    }
    return false;
  }
  return false;
}

