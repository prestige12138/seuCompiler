std::string joinedType(const std::vector<SemanticValue>& rhs) {
  static const std::vector<std::string> kTypeTokens = {
      "VOID", "CHAR", "SHORT", "INT", "LONG", "FLOAT", "DOUBLE", "SIGNED", "UNSIGNED", "BOOL", "STRUCT", "UNION", "ENUM", "TYPE_NAME"};
  std::string type;
  for (const SemanticValue& value : rhs) {
    if (std::find(kTypeTokens.begin(), kTypeTokens.end(), value.symbol) != kTypeTokens.end()) {
      if (!type.empty()) type += ' ';
      type += value.symbol;
    }
  }
  return type;
}

void observeReduction(int production, const std::vector<SemanticValue>& rhs, RuntimeSymbolTable* symbols) {
  if (symbols == nullptr) return;
  const std::string& left = kProductionLeft[static_cast<std::size_t>(production)];
  const std::string type = joinedType(rhs);
  if (left == "declaration" || left == "parameter_declaration" || left == "function_definition") {
    for (const SemanticValue& value : rhs) {
      if (value.symbol == "IDENTIFIER" && !value.lexeme.empty()) {
        RuntimeSymbol symbol;
        symbol.name = value.lexeme;
        symbol.type = type;
        symbol.is_function = left == "function_definition";
        symbol.is_parameter = left == "parameter_declaration";
        symbols->declareSymbol(symbol);
      }
    }
  }
}

